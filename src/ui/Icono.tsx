export type NombreIcono = keyof typeof ICONOS;

export function Icono({
  nombre,
  tam = 16,
  color,
  className,
  grosor = 2,
  titulo,
}: {
  nombre: NombreIcono;
  tam?: number;
  color?: string;
  className?: string;
  grosor?: number;
  /** Si se indica, el ícono deja de ser decorativo. */
  titulo?: string;
}) {
  const C = ICONOS[nombre];
  return (
    <C
      // en rem: los íconos escalan con la interfaz (80 %) igual que los estilos (vite.config.ts)
      size={`${tam / 16}rem`}
      color={color ?? 'currentColor'}
      strokeWidth={grosor}
      className={className}
      aria-hidden={titulo ? undefined : true}
      aria-label={titulo}
      role={titulo ? 'img' : undefined}
      focusable="false"
    />
  );
}
